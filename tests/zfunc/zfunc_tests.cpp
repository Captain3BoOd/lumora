// Tests for core/zfunc. Evidence label: unit tests only. Expected values come from the definitions: a C++ oracle that compares every candidate length
// (no window scan, no fall-back chain) for small and sampled strings, and golden digests from tools/zfunc_ref.py (independent Python) for the exhaustive
// sets and the large patterns. Large strings are also certified by a second computation: the border array rebuilt from the Z array must equal the border
// array of the library. No timing is asserted; overlapping arrays are not tested (unspecified).
