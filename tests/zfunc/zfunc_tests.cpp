struct Digest {
  std::uint64_t h = 0xcbf29ce484222325ull;
  void add(std::uint32_t v) {
    for (int b = 0; b < 4; ++b) {
      h ^= (v >> (8 * b)) & 0xFFu;
      h *= 0x100000001b3ull;
    }
  }
};

// Definition oracle: the longest common prefix of s and every suffix, and the longest proper border of every prefix, by comparing candidates.
U32s oracle_z(const Bytes& s) {
  U32s z(s.size());
  for (std::size_t i = 0; i < s.size(); ++i) {
    std::size_t k = 0;
    while (i + k < s.size() && s[k] == s[i + k]) ++k;
    z[i] = static_cast<std::uint32_t>(k);
  }
  return z;
}
U32s oracle_pi(const Bytes& s) {
  U32s p(s.size());
  for (std::size_t i = 0; i < s.size(); ++i) {
    std::size_t best = 0;
    for (std::size_t k = i; k >= 1; --k) {
      bool eq = true;
      for (std::size_t t = 0; t < k && eq; ++t) eq = s[t] == s[i + 1 - k + t];
      if (eq) {
        best = k;
        break;
      }
    }
    p[i] = static_cast<std::uint32_t>(best);
  }
  return p;
}

// Run both functions with sentinel words around the output arrays. Returns false on any sentinel damage or a non-Ok result.
bool run(const Bytes& s, U32s& z, U32s& p) {
  const std::uint32_t n = static_cast<std::uint32_t>(s.size());
  U32s zb(n + 2, 0xDEADBEEFu), pb(n + 2, 0xDEADBEEFu);
  const std::uint8_t dummy = 0;
  const std::uint8_t* sp = n ? s.data() : &dummy;
  if (zfunc_z(n, sp, zb.data() + 1) != ZResult::Ok) return false;
  if (zfunc_pi(n, sp, pb.data() + 1) != ZResult::Ok) return false;
  if (zb[0] != 0xDEADBEEFu || zb[n + 1] != 0xDEADBEEFu || pb[0] != 0xDEADBEEFu || pb[n + 1] != 0xDEADBEEFu) return false;
  z.assign(zb.begin() + 1, zb.begin() + 1 + n);
  p.assign(pb.begin() + 1, pb.begin() + 1 + n);
  return true;
}

std::uint64_t digest_of(const Bytes& s, Digest& d) {
  U32s z, p;
  REQUIRE(run(s, z, p));
  for (auto v : z) d.add(v);
  for (auto v : p) d.add(v);
  return d.h;
}

// Border array rebuilt from the Z array (a different computation than the library's border scan).
U32s pi_from_z(const U32s& z) {
  U32s p(z.size(), 0);
  for (std::size_t i = 1; i < z.size(); ++i) {
    for (std::int64_t j = static_cast<std::int64_t>(z[i]) - 1; j >= 0 && p[i + static_cast<std::size_t>(j)] == 0; --j) p[i + static_cast<std::size_t>(j)] = static_cast<std::uint32_t>(j + 1);
  }
  return p;
}

// All strings of length 0 .. maxlen over alpha, shortest first, first symbol most significant (the order of tools/zfunc_ref.py).
template <class F>
void each_string(const std::vector<std::uint8_t>& alpha, unsigned maxlen, F f) {
  for (unsigned len = 0; len <= maxlen; ++len) {
    std::vector<unsigned> idx(len, 0);
    for (;;) {
      Bytes s(len);
      for (unsigned i = 0; i < len; ++i) s[i] = alpha[idx[i]];
      f(s);
      int pos = static_cast<int>(len) - 1;
      while (pos >= 0 && ++idx[static_cast<unsigned>(pos)] == alpha.size()) idx[static_cast<unsigned>(pos--)] = 0;
      if (pos < 0) break;
    }
  }
}

Bytes lcg(std::uint32_t seed, std::size_t n, unsigned k) {
  std::uint64_t x = seed;
  Bytes out(n);
  for (auto& b : out) {
    x = (x * 1103515245ull + 12345ull) & 0x7FFFFFFFull;
    b = static_cast<std::uint8_t>(((x >> 16) % k));
  }
  return out;
}

Bytes fib(std::size_t n) {
  Bytes a{0}, b{0, 1};
  while (b.size() < n) {
    Bytes c = b;
    c.insert(c.end(), a.begin(), a.end());
    a = b;
    b = c;
  }
  b.resize(n);
  return b;
}

struct Large {
  const char* name;
  Bytes s;
};
std::vector<Large> large_patterns() {
  const std::size_t N = 262144;
  Bytes alt(N - 1);
  for (std::size_t i = 0; i < alt.size(); ++i) alt[i] = (i % 2 == 0) ? 0 : 255;
  Bytes zo(N - 1, 0);
  zo.push_back(1);
  Bytes oz(N, 0);
  oz[0] = 1;
  Bytes blk = lcg(77, 1000, 256), rep;
  for (std::size_t i = 0; i < N; ++i) rep.push_back(blk[i % 1000]);
  return {{"rep0", Bytes(N, 0)}, {"alt", alt}, {"zeros_one", zo}, {"one_zeros", oz}, {"fib", fib(N)}, {"rand2", lcg(11, N, 2)}, {"rand256", lcg(12, N, 256)}, {"block1000", rep}};
}

bool lookup(const char* name, Row& out) {
  for (const Row& r : kDigests)
    if (std::string(r.name) == name) {
      out = r;
      return true;
    }
  return false;
}
