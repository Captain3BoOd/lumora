constexpr std::uint32_t kSentinel = 0xDEADBEEFu;

std::uint32_t code(Utf8Result r) { return static_cast<std::uint32_t>(r); }

struct Fold {
  std::uint64_t h = 0xCBF29CE484222325ull;
  std::size_t n = 0;
  void add(std::uint64_t v) {
    ++n;
    h = (h ^ v) * 0x100000001B3ull;
  }
};

struct Outcome {
  std::uint32_t vs = 0, off = 0, ds = 0, cp = 0, ln = 0;
  bool sentinel_ok = true;
  bool operator==(const Outcome& o) const { return vs == o.vs && off == o.off && ds == o.ds && cp == o.cp && ln == o.ln; }
  std::uint64_t pack() const {
    return static_cast<std::uint64_t>(vs) | (static_cast<std::uint64_t>(off) << 4) | (static_cast<std::uint64_t>(ds) << 8) |
           (static_cast<std::uint64_t>(ln) << 12) | (static_cast<std::uint64_t>(cp) << 16);
  }
};

// the real functions on the n bytes at p (p must be a heap buffer of exactly n bytes)
Outcome run_impl(const std::uint8_t* p, std::uint32_t n) {
  Outcome o;
  std::uint32_t off = kSentinel;
  o.vs = code(validate(p, n, &off));
  o.off = off;
  std::uint32_t cp = kSentinel, ln = kSentinel;
  o.ds = code(decode_one(p, n, &cp, &ln));
  if (o.ds == 0) {
    o.cp = cp;
    o.ln = ln;
  } else {
    o.sentinel_ok = cp == kSentinel && ln == kSentinel;
  }
  return o;
}

// oracle: decode by lead pattern and shifts, reject by value
bool oracle_decode(const std::uint8_t* p, std::size_t avail, std::uint32_t& cp, std::uint32_t& ln) {
  if (avail == 0) return false;
  const std::uint32_t b = p[0];
  std::uint32_t len = 0, v = 0, min = 0;
  if (b < 0x80u) {
    cp = b;
    ln = 1;
    return true;
  }
  if ((b & 0xE0u) == 0xC0u) {
    len = 2;
    v = b & 0x1Fu;
    min = 0x80u;
  } else if ((b & 0xF0u) == 0xE0u) {
    len = 3;
    v = b & 0x0Fu;
    min = 0x800u;
  } else if ((b & 0xF8u) == 0xF0u) {
    len = 4;
    v = b & 0x07u;
    min = 0x10000u;
  } else {
    return false;
  }
  if (avail < len) return false;
  for (std::uint32_t k = 1; k < len; ++k) {
    if ((p[k] & 0xC0u) != 0x80u) return false;
    v = v * 64u + (p[k] & 0x3Fu);
  }
  if (v < min || v > 0x10FFFFu || (v >= 0xD800u && v <= 0xDFFFu)) return false;
  cp = v;
  ln = len;
  return true;
}

Outcome run_oracle(const std::uint8_t* p, std::uint32_t n) {
  Outcome o;
  std::uint32_t i = 0;
  o.vs = 0;
  o.off = n;
  while (i < n) {
    std::uint32_t cp = 0, ln = 0;
    if (!oracle_decode(p + i, n - i, cp, ln)) {
      o.vs = 4;
      o.off = i;
      break;
    }
    i += ln;
  }
  std::uint32_t cp = 0, ln = 0;
  if (n > 0 && oracle_decode(p, n, cp, ln)) {
    o.ds = 0;
    o.cp = cp;
    o.ln = ln;
  } else {
    o.ds = 4;
  }
  return o;
}

// oracle encode: groups of 6 bits from the low end
std::vector<std::uint8_t> oracle_encode(std::uint32_t cp) {
  std::vector<std::uint8_t> out;
  if (cp > 0x10FFFFu || (cp >= 0xD800u && cp <= 0xDFFFu)) return out;
  const std::uint32_t len = cp < 0x80u ? 1u : cp < 0x800u ? 2u : cp < 0x10000u ? 3u : 4u;
  out.assign(len, 0);
  std::uint32_t v = cp;
  for (std::uint32_t i = len; i-- > 1;) {
    out[i] = static_cast<std::uint8_t>(0x80u + v % 64u);
    v /= 64u;
  }
  const std::uint32_t prefix[] = {0u, 0u, 0xC0u, 0xE0u, 0xF0u};
  out[0] = static_cast<std::uint8_t>(prefix[len] + v);
  return out;
}

// compares one input with the oracle, checks that an accepted sequence re-encodes to the same bytes; returns the number of mismatches
std::size_t check_input(const std::uint8_t* p, std::uint32_t n, Fold* f) {
  const Outcome a = run_impl(p, n);
  const Outcome b = run_oracle(p, n);
  std::size_t bad = 0;
  if (!(a == b) || !a.sentinel_ok) ++bad;
  if (a.ds == 0) {
    std::uint8_t out[4] = {0xAA, 0xAA, 0xAA, 0xAA};
    std::uint32_t ln = 0;
    if (encode_one(a.cp, out, 4, &ln) != Utf8Result::Ok || ln != a.ln) {
      ++bad;
    } else {
      for (std::uint32_t k = 0; k < ln; ++k)
        if (out[k] != p[k]) ++bad;
    }
  }
  if (f != nullptr) f->add(a.pack());
  return bad;
}

