struct Row {
  const char* name;
  u64 count, digest;
};
const Row kDigests[] = {
    {"nth_small", 780, 0x984dc26ac38b01ee},
    {"nth_mid", 96, 0xb636ea30a45c93b0},
    {"nth_big", 21, 0x340118d95e7adbeb},
    {"nth_iter", 18, 0x6bae609ec87e2207},
    {"bm_ter", 9841, 0x5d7f0a4d896c0284},
    {"bm_ext", 5461, 0x0bb4f2957166561a},
    {"bm_rec", 155, 0xfbbde0942bc06c1d},
    {"bm_rand", 60, 0x20cfc55cb0696046},
    {"bm_big", 8, 0x3865e8934c660f43},
};
const Row& row(const char* name) {
  for (const Row& r : kDigests) {
    if (std::string(r.name) == name) return r;
  }
  FAIL("unknown digest row");
  return kDigests[0];
}

struct Digest {
  u64 h = 0xcbf29ce484222325ull;
  u64 count = 0;
  void add(u32 v) {
    for (int b = 0; b < 4; ++b) {
      h ^= (v >> (8 * b)) & 0xFFu;
      h *= 0x100000001b3ull;
    }
  }
};

struct SM {
  u64 s;
  explicit SM(u64 seed) : s(seed) {}
  u64 next() {
    s += 0x9E3779B97F4A7C15ull;
    u64 z = s;
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
    return z ^ (z >> 31);
  }
  u32 res() {
    const u64 v = next();
    switch (v & 7u) {
      case 0: return 0u;
      case 1: return 1u;
      case 2: return kMod - 1u;
      case 3: return kMod - 2u;
      case 4: return 2u;
      default: return static_cast<u32>((v >> 3) % kMod);
    }
  }
};

u32 mulm(u32 a, u32 b) { return static_cast<u32>(static_cast<u64>(a) * static_cast<u64>(b) % kMod); }
u32 addm(u32 a, u32 b) { return static_cast<u32>((static_cast<u64>(a) + b) % kMod); }

// Oracle: the recurrence iterated term by term (terms 0 .. count-1).
U32s iterate(const U32s& coef, const U32s& init, std::size_t count) {
  U32s a(init);
  const std::size_t d = coef.size();
  while (a.size() < count) {
    const std::size_t k = a.size();
    u32 acc = 0;
    for (std::size_t j = 0; j < d; ++j) acc = addm(acc, mulm(coef[j], a[k - 1 - j]));
    a.push_back(acc);
  }
  return a;
}

// nth through the library with exact scratch (odd word offset) and a sentinel around the result. Returns false on a non-Ok result.
bool nth(const U32s& coef, const U32s& init, u64 n, u32& out) {
  const u32 d = static_cast<u32>(coef.size());
  U32s scratch(4u * d + 3u, 0xDEADBEEFu);
  const u32 dummy = 0;
  u32 res = 0xDEADBEEFu;
  const LinResult r = linrec_nth(d ? coef.data() : &dummy, d ? init.data() : &dummy, d, n, scratch.data() + 1, 4u * d, &res);
  if (r != LinResult::Ok) return false;
  out = res;
  return true;
}

// Generation property: seq[k] equals the recurrence for every k from L to len-1.
bool generates(const U32s& coef, const U32s& seq) {
  const std::size_t L = coef.size();
  for (std::size_t k = L; k < seq.size(); ++k) {
    u32 acc = 0;
    for (std::size_t j = 0; j < L; ++j) acc = addm(acc, mulm(coef[j], seq[k - 1 - j]));
    if (acc != seq[k]) return false;
  }
  return true;
}

// bm through the library with exact scratch and exact output capacity, sentinels around the coefficient array.
bool bm(const U32s& seq, u32& L, U32s& coef) {
  const u32 len = static_cast<u32>(seq.size());
  U32s scratch(3u * len + 5u, 0xDEADBEEFu);
  const u32 dummy = 0;
  u32 d1 = 0xDEADBEEFu;
  // first a run with a huge capacity to learn L
  U32s big(len + 2u, 0xDEADBEEFu);
  if (linrec_bm(len ? seq.data() : &dummy, len, scratch.data() + 1, len ? 3u * len + 3u : 0u, big.data() + 1, len, &d1) != LinResult::Ok) return false;
  L = d1;
  if (L > len) return false;
  if (big[0] != 0xDEADBEEFu) return false;
  for (u32 i = L; i < len + 1u; ++i) {
    if (big[1 + i] != 0xDEADBEEFu) return false;  // nothing past out_coef[L - 1] may be written
  }
  // exact capacity must give the same; capacity L - 1 must fail without writes
  U32s ex(L + 2u, 0xDEADBEEFu);
  u32 d2 = 0xDEADBEEFu;
  if (linrec_bm(len ? seq.data() : &dummy, len, scratch.data() + 1, len ? 3u * len + 3u : 0u, ex.data() + 1, L, &d2) != LinResult::Ok) return false;
  if (d2 != L || ex[0] != 0xDEADBEEFu || ex[L + 1] != 0xDEADBEEFu) return false;
  if (L > 0) {
    U32s sm(L + 2u, 0xDEADBEEFu);
    u32 d3 = 0xDEADBEEFu;
    if (linrec_bm(seq.data(), len, scratch.data() + 1, 3u * len + 3u, sm.data() + 1, L - 1u, &d3) != LinResult::OutTooSmall) return false;
    if (d3 != 0xDEADBEEFu) return false;
    for (u32 v : sm) {
      if (v != 0xDEADBEEFu) return false;
    }
  }
  coef.assign(ex.begin() + 1, ex.begin() + 1 + L);
  return true;
}

void emit_bm(Digest& dg, const U32s& seq) {
  u32 L = 0;
  U32s coef;
  REQUIRE(bm(seq, L, coef));
  REQUIRE(generates(coef, seq));
  dg.add(L);
  if (2u * L <= seq.size()) {
    for (u32 c : coef) dg.add(c);
  }
  ++dg.count;
}

void check_digest(const char* name, const Digest& dg) {
  const Row& r = row(name);
  CHECK(dg.count == r.count);
  CHECK(dg.h == r.digest);
}

U32s from_recurrence(SM& r, u32 order, std::size_t len) {
  U32s coef, init;
  for (u32 i = 0; i < order; ++i) coef.push_back(r.res());
  for (u32 i = 0; i < order; ++i) init.push_back(r.res());
  if (order == 0) return U32s(len, 0u);
  U32s a = iterate(coef, init, len);
  a.resize(len);
  return a;
}

template <class F>
void each_sequence(const U32s& alpha, unsigned maxlen, F f) {
  for (unsigned len = 0; len <= maxlen; ++len) {
    std::vector<unsigned> idx(len, 0);
    for (;;) {
      U32s s(len);
      for (unsigned i = 0; i < len; ++i) s[i] = alpha[idx[i]];
      f(s);
      int pos = static_cast<int>(len) - 1;
      while (pos >= 0 && ++idx[static_cast<unsigned>(pos)] == alpha.size()) idx[static_cast<unsigned>(pos--)] = 0;
      if (pos < 0) break;
    }
  }
}
